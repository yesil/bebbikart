// Writes the shared contract data the Godot game needs, since it can't import JS:
//   apps/game/net/protocol.gd           enums, message types, protocol version
//   apps/game/data/racer_kit.json       kit catalog + spec limits
//   apps/game/data/pkg_default/spec.json the default racer
// Run with `bun run kit:export` after changing packages/shared.
import { mkdir } from "node:fs/promises";
import { join } from "node:path";
import * as enums from "../src/enums.js";
import {
  DEFAULT_BUILD,
  DEFAULT_CONFIG,
  DEFAULT_SPEC,
  MESSAGE_TYPES,
  RACER_KIT,
  SPEC_LIMITS,
} from "../src/index.js";

const gameDir = join(import.meta.dir, "../../../apps/game");

const constName = (name) => name.replace(/([a-z])([A-Z])/g, "$1_$2").toUpperCase();
const gd = (value) => JSON.stringify(value, null, "\t");

const lines = [
  "# GENERATED by packages/shared/scripts/export-godot.js — do not edit by hand.",
  "# Source of truth: docs/contracts.md and packages/shared.",
  "class_name Protocol",
  "",
];
for (const [name, value] of Object.entries(enums)) {
  lines.push(`const ${constName(name)} = ${gd(value)}`);
}
lines.push(`const DEFAULT_CONFIG = ${gd(DEFAULT_CONFIG)}`);
lines.push(`const DEFAULT_BUILD = ${gd(DEFAULT_BUILD)}`);
lines.push("");
for (const [channel, types] of Object.entries(MESSAGE_TYPES)) {
  lines.push(`const MSG_${constName(channel)} = ${gd(types)}`);
}
lines.push("");

await mkdir(join(gameDir, "net"), { recursive: true });
await mkdir(join(gameDir, "data/pkg_default"), { recursive: true });
await Bun.write(join(gameDir, "net/protocol.gd"), lines.join("\n"));
await Bun.write(
  join(gameDir, "data/racer_kit.json"),
  `${JSON.stringify({ ...RACER_KIT, limits: SPEC_LIMITS }, null, 2)}\n`,
);
await Bun.write(
  join(gameDir, "data/pkg_default/spec.json"),
  `${JSON.stringify(DEFAULT_SPEC, null, 2)}\n`,
);
console.log("Wrote protocol.gd, racer_kit.json and pkg_default/spec.json to apps/game");
